-- =====================================================================
--  Sunwai - AI-Routed Grievance Redressal System for NSUT
--  01_schema.sql : DDL for all 28 tables
--
--  Naming: the design document uses CamelCase (e.g. CommitteeMember);
--  PostgreSQL convention is snake_case, so CommitteeMember -> committee_member.
--
--  Part 1 (people, organisation, committees, academics, exams) : 12 tables
--  Part 2 (complaint pipeline)                                 : 16 tables
-- =====================================================================

SET client_min_messages = warning;
DROP SCHEMA IF EXISTS sunwai CASCADE;
CREATE SCHEMA sunwai;
SET search_path TO sunwai, public;
SET client_min_messages = warning;

-- ---------------------------------------------------------------------
--  PART 1 : PEOPLE, ORGANISATION, COMMITTEES, ACADEMICS, EXAMS
-- ---------------------------------------------------------------------

-- 1. Department : departments, hostels, offices and cells as one tree.
--    Recursive relationship Sub_Unit_Of via parent_unit_id.
CREATE TABLE department (
    unit_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(60)  NOT NULL UNIQUE,
    unit_type       VARCHAR(12)  NOT NULL
                    CHECK (unit_type IN ('University','Academic','Hostel','Office','Cell')),
    campus          VARCHAR(10)  NOT NULL DEFAULT 'Main'
                    CHECK (campus IN ('Main','East','West')),
    parent_unit_id  INT REFERENCES department(unit_id) ON DELETE RESTRICT,
    CHECK (parent_unit_id IS NULL OR parent_unit_id <> unit_id)
);

-- 2. Person : supertype of Student and Faculty (ISA). Staff stay as plain Persons.
CREATE TABLE person (
    person_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   VARCHAR(40) NOT NULL,
    last_name    VARCHAR(40) NOT NULL,
    email        VARCHAR(80) NOT NULL UNIQUE,
    phone        VARCHAR(15),
    person_type  VARCHAR(10) NOT NULL CHECK (person_type IN ('Student','Faculty','Staff')),
    unit_id      INT NOT NULL REFERENCES department(unit_id)          -- Belongs_To (total)
);

-- 3. Student (ISA subtype of Person)
CREATE TABLE student (
    person_id       INT PRIMARY KEY REFERENCES person(person_id) ON DELETE CASCADE,
    roll_no         VARCHAR(15) NOT NULL UNIQUE,
    programme       VARCHAR(30) NOT NULL,
    batch_year      INT NOT NULL CHECK (batch_year BETWEEN 2000 AND 2100),
    hostel_unit_id  INT REFERENCES department(unit_id),               -- Lives_In (partial)
    room_no         VARCHAR(10)
);

-- 4. Faculty (ISA subtype of Person)
CREATE TABLE faculty (
    person_id      INT PRIMARY KEY REFERENCES person(person_id) ON DELETE CASCADE,
    employee_code  VARCHAR(15) NOT NULL UNIQUE,
    designation    VARCHAR(40) NOT NULL
);

-- 5. Position : posts such as "Caretaker BH-3" or "HOD CSE".
--    holder_id = current holder; reports_to = recursive reporting hierarchy
--    (drives escalation and the conflict-of-interest check).
CREATE TABLE position (
    position_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(60) NOT NULL UNIQUE,
    role_code    VARCHAR(25) NOT NULL CHECK (role_code IN (
                   'Caretaker','Warden','ChiefWarden','HOD','LabInCharge',
                   'TimetableCoordinator','DeptAdmin','EstateOfficer',
                   'ComputerCentreStaff','ComputerCentreHead','DeanAcademics',
                   'DeanStudentWelfare','CoE','Registrar','TriageOfficer',
                   'Proctor','ViceChancellor')),
    unit_id      INT REFERENCES department(unit_id),                  -- NULL for central posts
    holder_id    INT REFERENCES person(person_id) ON DELETE SET NULL,
    reports_to   INT REFERENCES position(position_id),
    CHECK (reports_to IS NULL OR reports_to <> position_id)
);

-- 6. Committee
CREATE TABLE committee (
    committee_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(80) NOT NULL UNIQUE,
    committee_type  VARCHAR(15) NOT NULL UNIQUE
                    CHECK (committee_type IN ('ICC','AntiRagging','SGRC','Ombudsperson')),
    quorum          INT NOT NULL CHECK (quorum >= 1)
);

-- 7. CommitteeMember : M:N Person x Committee with attributes
CREATE TABLE committee_member (
    committee_id  INT REFERENCES committee(committee_id) ON DELETE CASCADE,
    person_id     INT REFERENCES person(person_id) ON DELETE CASCADE,
    member_role   VARCHAR(15) NOT NULL DEFAULT 'Member'
                  CHECK (member_role IN ('Chair','Member','StudentInvitee')),
    term_start    DATE NOT NULL,
    term_end      DATE,
    PRIMARY KEY (committee_id, person_id),
    CHECK (term_end IS NULL OR term_end > term_start)
);

-- 8. Course
CREATE TABLE course (
    course_code  VARCHAR(10) PRIMARY KEY,
    title        VARCHAR(80) NOT NULL,
    credits      INT NOT NULL CHECK (credits BETWEEN 1 AND 6),
    unit_id      INT NOT NULL REFERENCES department(unit_id)          -- Offers (total)
);

-- 9. CourseOffering : a course taught by one faculty in one semester/section
CREATE TABLE course_offering (
    offering_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code  VARCHAR(10) NOT NULL REFERENCES course(course_code),
    faculty_id   INT NOT NULL REFERENCES faculty(person_id),          -- Teaches
    semester     VARCHAR(10) NOT NULL,
    section      VARCHAR(5)  NOT NULL,
    UNIQUE (course_code, semester, section)
);

-- 10. Enrollment : M:N Student x CourseOffering
CREATE TABLE enrollment (
    student_id   INT REFERENCES student(person_id) ON DELETE CASCADE,
    offering_id  INT REFERENCES course_offering(offering_id) ON DELETE CASCADE,
    PRIMARY KEY (student_id, offering_id)
);

-- 11. Exam
CREATE TABLE exam (
    exam_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offering_id  INT NOT NULL REFERENCES course_offering(offering_id),
    exam_type    VARCHAR(10) NOT NULL CHECK (exam_type IN ('MidSem','EndSem')),
    exam_date    DATE NOT NULL,
    max_marks    INT  NOT NULL CHECK (max_marks > 0),
    UNIQUE (offering_id, exam_type)
);

-- 12. AnswerScript : one student's script, evaluated by one faculty member
CREATE TABLE answer_script (
    script_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id       INT NOT NULL REFERENCES exam(exam_id),
    student_id    INT NOT NULL REFERENCES student(person_id),
    evaluator_id  INT NOT NULL REFERENCES faculty(person_id),
    total_marks   NUMERIC(5,2) NOT NULL CHECK (total_marks >= 0),
    shown_on      DATE,
    UNIQUE (exam_id, student_id)
);

-- ---------------------------------------------------------------------
--  PART 2 : COMPLAINT PIPELINE
-- ---------------------------------------------------------------------

-- 13. Category : complaint types with priority, deadline and sensitivity
CREATE TABLE category (
    category_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(60) NOT NULL UNIQUE,
    domain              VARCHAR(25) NOT NULL CHECK (domain IN (
                          'Hostel','Mess','Infrastructure','LabEquipment','Academic',
                          'Exam','IT','FacultyConduct','Harassment','Ragging',
                          'Discrimination','General')),
    sensitivity         VARCHAR(10) NOT NULL DEFAULT 'Normal'
                        CHECK (sensitivity IN ('Normal','Sensitive')),
    base_priority       VARCHAR(6)  CHECK (base_priority IN ('Low','Medium','High')),
                        -- NULL for General/Other: priority then comes from AI urgency
    sla_hours           INT CHECK (sla_hours > 0),
                        -- NULL: deadline is derived from priority instead
    anonymous_allowed   BOOLEAN NOT NULL DEFAULT FALSE,
    appeal_window_days  INT NOT NULL DEFAULT 15 CHECK (appeal_window_days >= 0)
);

-- 14. CategoryRequirement : weak entity of Category (partial key field_name).
--     The rulebook for the completeness check.
CREATE TABLE category_requirement (
    category_id      INT REFERENCES category(category_id) ON DELETE CASCADE,
    field_name       VARCHAR(30),
    is_mandatory     BOOLEAN NOT NULL,
    question_prompt  VARCHAR(200) NOT NULL,
    PRIMARY KEY (category_id, field_name)
);

-- 15. RoutingRule : category -> role (resolved against the complaint's unit)
--     or -> committee. Exactly one target.
CREATE TABLE routing_rule (
    rule_id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id          INT NOT NULL REFERENCES category(category_id) ON DELETE CASCADE,
    target_role_code     VARCHAR(25),
    target_committee_id  INT REFERENCES committee(committee_id),
    priority             INT NOT NULL DEFAULT 1,
    CHECK ((target_role_code IS NULL) <> (target_committee_id IS NULL)),
    UNIQUE (category_id, priority)
);

-- 16. Complaint
CREATE TABLE complaint (
    complaint_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description         TEXT NOT NULL CHECK (length(trim(description)) >= 5),
    visibility          VARCHAR(12) NOT NULL DEFAULT 'Public'
                        CHECK (visibility IN ('Public','Confidential','Anonymous')),
    status              VARCHAR(15) NOT NULL DEFAULT 'Filed' CHECK (status IN (
                          'Filed','Triaged','NeedsInfo','Assigned','InProgress',
                          'Escalated','Resolved','Rejected','Closed','Appealed')),
    priority            VARCHAR(6) CHECK (priority IN ('Low','Medium','High')),
    filed_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    category_id         INT REFERENCES category(category_id),      -- final, human-confirmed
    unit_id             INT REFERENCES department(unit_id),        -- where it happened
    location_text       VARCHAR(100),
    offering_id         INT REFERENCES course_offering(offering_id),
    script_id           INT REFERENCES answer_script(script_id),
    reopened_from       INT REFERENCES complaint(complaint_id),    -- recursive (Reopens)
    resolution_outcome  VARCHAR(20) CHECK (resolution_outcome IN
                          ('Upheld','Dismissed','ActionTaken','Fixed','InsufficientInfo')),
    resolution_note     VARCHAR(300),
    resolved_at         TIMESTAMPTZ,
    feedback_rating     INT CHECK (feedback_rating BETWEEN 1 AND 5),
    CHECK (reopened_from IS NULL OR reopened_from <> complaint_id),
    CHECK (resolved_at IS NULL OR resolved_at >= filed_at)
);

-- 17. ComplainantIdentity : who filed, kept apart so DCL can lock it down
CREATE TABLE complainant_identity (
    complaint_id     INT PRIMARY KEY REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    person_id        INT NOT NULL REFERENCES person(person_id),
    contact_consent  BOOLEAN NOT NULL DEFAULT TRUE
);

-- 18. ComplaintParty : people named in a complaint (respondent / witness).
--     person_id may be NULL when the person could not be identified.
CREATE TABLE complaint_party (
    complaint_id  INT REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    party_no      INT,
    person_id     INT REFERENCES person(person_id),
    party_role    VARCHAR(10) NOT NULL CHECK (party_role IN ('Respondent','Witness')),
    stated_role   VARCHAR(10) NOT NULL DEFAULT 'Unknown'
                  CHECK (stated_role IN ('Student','Faculty','Staff','Unknown')),
    description   VARCHAR(150),
    PRIMARY KEY (complaint_id, party_no),
    CHECK (person_id IS NOT NULL OR description IS NOT NULL OR stated_role <> 'Unknown')
);

-- 19. ComplaintDetail : one row per extracted detail (keeps the data atomic / 1NF)
CREATE TABLE complaint_detail (
    complaint_id  INT REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    field_name    VARCHAR(30),
    value         VARCHAR(200) NOT NULL,
    source        VARCHAR(10) NOT NULL CHECK (source IN ('AI','Profile','User','Handler')),
    PRIMARY KEY (complaint_id, field_name)
);

-- 20. AITriageResult : 1:1 with Complaint (UNIQUE FK)
CREATE TABLE ai_triage_result (
    triage_id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id           INT NOT NULL UNIQUE REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    suggested_category_id  INT REFERENCES category(category_id),
    urgency                VARCHAR(6) NOT NULL CHECK (urgency IN ('Low','Medium','High')),
    confidence             NUMERIC(3,2) NOT NULL CHECK (confidence BETWEEN 0 AND 1),
    sensitivity_flag       BOOLEAN NOT NULL DEFAULT FALSE,
    summary                VARCHAR(300),
    reviewed_by            INT REFERENCES person(person_id),
    reviewed_at            TIMESTAMPTZ
);

-- 21. Clarification : weak entity of Complaint (partial key seq_no)
CREATE TABLE clarification (
    complaint_id  INT REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    seq_no        INT,
    field_name    VARCHAR(30),
    question      VARCHAR(200) NOT NULL,
    asked_by      VARCHAR(10) NOT NULL CHECK (asked_by IN ('AI','Handler')),
    answer        VARCHAR(300),
    asked_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    answered_at   TIMESTAMPTZ,
    PRIMARY KEY (complaint_id, seq_no),
    CHECK ((answer IS NULL) = (answered_at IS NULL))
);

-- 22. StatusHistory : weak entity of Complaint (append-only, written by trigger)
CREATE TABLE status_history (
    complaint_id  INT REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    seq_no        INT,
    old_status    VARCHAR(15),
    new_status    VARCHAR(15) NOT NULL,
    changed_by    INT REFERENCES person(person_id),
    changed_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    note          VARCHAR(200),
    PRIMARY KEY (complaint_id, seq_no)
);

-- 23. AccessLog : every read of a confidential/sensitive complaint
CREATE TABLE access_log (
    log_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id  INT NOT NULL REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    accessed_by   INT REFERENCES person(person_id),
    db_role       VARCHAR(25) NOT NULL,
    action        VARCHAR(10) NOT NULL CHECK (action IN ('View','Update','Export')),
    accessed_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 24. RoutingDecision : who got the complaint, why, and by when.
--     Initial routing, escalations and manual re-routes are all rows here.
CREATE TABLE routing_decision (
    decision_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id           INT NOT NULL REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    rule_id                INT REFERENCES routing_rule(rule_id),
    assigned_person_id     INT REFERENCES person(person_id),
    assigned_committee_id  INT REFERENCES committee(committee_id),
    decision_type          VARCHAR(12) NOT NULL
                           CHECK (decision_type IN ('Initial','Escalation','Reroute','Manual')),
    reason                 VARCHAR(300) NOT NULL,
    decided_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    due_at                 TIMESTAMPTZ,
    CHECK ((assigned_person_id IS NULL) <> (assigned_committee_id IS NULL)),
    CHECK (due_at IS NULL OR due_at > decided_at)
);

-- 25. ConflictExclusion : M:N RoutingDecision x Person with the reason
CREATE TABLE conflict_exclusion (
    decision_id  INT REFERENCES routing_decision(decision_id) ON DELETE CASCADE,
    person_id    INT REFERENCES person(person_id),
    reason_code  VARCHAR(25) NOT NULL CHECK (reason_code IN (
                   'Respondent','ReportsToRespondent','Complainant',
                   'SameDepartment','OriginalEvaluator')),
    PRIMARY KEY (decision_id, person_id)
);

-- 26. Appeal : appeal of a decision, heard by the Ombudsperson
CREATE TABLE appeal (
    appeal_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id  INT NOT NULL REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    appellant_id  INT NOT NULL REFERENCES person(person_id),
    heard_by      INT REFERENCES person(person_id),
    filed_on      DATE NOT NULL DEFAULT current_date,
    grounds       TEXT NOT NULL,
    status        VARCHAR(12) NOT NULL DEFAULT 'Pending'
                  CHECK (status IN ('Pending','Upheld','Dismissed')),
    outcome       VARCHAR(300),
    CHECK (heard_by IS NULL OR heard_by <> appellant_id)
);

-- 27. QuestionDispute : weak entity of Complaint (partial key question_no)
CREATE TABLE question_dispute (
    complaint_id       INT REFERENCES complaint(complaint_id) ON DELETE CASCADE,
    question_no        INT CHECK (question_no > 0),
    marks_awarded      NUMERIC(4,1) NOT NULL CHECK (marks_awarded >= 0),
    marks_claimed      NUMERIC(4,1) NOT NULL CHECK (marks_claimed >= 0),
    student_reason     VARCHAR(300) NOT NULL,
    reviewer_decision  VARCHAR(10) CHECK (reviewer_decision IN ('Accepted','Rejected','Partial')),
    revised_marks      NUMERIC(4,1) CHECK (revised_marks >= 0),
    PRIMARY KEY (complaint_id, question_no),
    CHECK (marks_claimed > marks_awarded),
    CHECK ((reviewer_decision IS NULL) OR (revised_marks IS NOT NULL))
);

-- 28. MarksChangeLog : permanent record of every mark change (append-only)
CREATE TABLE marks_change_log (
    change_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    script_id     INT NOT NULL REFERENCES answer_script(script_id),
    complaint_id  INT NOT NULL REFERENCES complaint(complaint_id),
    question_no   INT NOT NULL,
    old_marks     NUMERIC(4,1) NOT NULL,
    new_marks     NUMERIC(4,1) NOT NULL,
    changed_by    INT NOT NULL REFERENCES faculty(person_id),
    changed_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    reason        VARCHAR(200) NOT NULL
);

-- ---------------------------------------------------------------------
--  INDEXES (on foreign keys used by routing, queues and RLS policies)
-- ---------------------------------------------------------------------
CREATE INDEX idx_person_unit            ON person(unit_id);
CREATE INDEX idx_position_holder        ON position(holder_id);
CREATE INDEX idx_position_unit_role     ON position(unit_id, role_code);
CREATE INDEX idx_position_reports_to    ON position(reports_to);
CREATE INDEX idx_offering_faculty       ON course_offering(faculty_id);
CREATE INDEX idx_complaint_status       ON complaint(status);
CREATE INDEX idx_complaint_category     ON complaint(category_id);
CREATE INDEX idx_complaint_unit         ON complaint(unit_id);
CREATE INDEX idx_identity_person        ON complainant_identity(person_id);
CREATE INDEX idx_party_person           ON complaint_party(person_id);
CREATE INDEX idx_decision_complaint     ON routing_decision(complaint_id, decided_at DESC);
CREATE INDEX idx_decision_person        ON routing_decision(assigned_person_id);
CREATE INDEX idx_decision_committee     ON routing_decision(assigned_committee_id);
CREATE INDEX idx_access_log_complaint   ON access_log(complaint_id);
CREATE INDEX idx_marks_log_script       ON marks_change_log(script_id);
